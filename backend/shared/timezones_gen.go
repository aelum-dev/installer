//go:build ignore

// This file is meant to be run with: go run ./backend/shared/timezones_gen.go
// It regenerates timezones_table.go — the time zones the installer offers.
//
// The list is every distinct civil clock tzdata has kept since 1970
// (zone1970.tab), plus UTC, plus the local names the installer's PreferredZone
// table writes for countries whose only tzdata row is named after a neighbour's
// city (Europe/Copenhagen, Atlantic/Reykjavik): those are valid TZ values and
// they are the name the install writes, so they must be selectable.
//
// The time zone is now a first-class choice on the Welcome page rather than a
// hidden consequence of the location, so the whole set is offered, not one zone
// per country. The location still pre-fills it (Region.Timezone); this table is
// what a person can change it to.
//
// ZONE_TABLE_PATH overrides the tzdata file when it is not where Arch puts it.

package main

import (
	"bufio"
	"fmt"
	"os"
	"sort"
	"strings"

	"aelum-installer/backend/shared"
)

func main() {
	if err := os.Chdir("backend/shared"); err != nil {
		fmt.Fprintf(os.Stderr, "Error changing directory: %v\n", err)
		os.Exit(1)
	}

	zonePath := os.Getenv("ZONE_TABLE_PATH")
	if zonePath == "" {
		zonePath = shared.ZoneTablePath
	}

	if err := generate(zonePath); err != nil {
		fmt.Fprintf(os.Stderr, "Error: %v\n", err)
		os.Exit(1)
	}
}

func generate(zonePath string) error {
	zones := map[string]*shared.Timezone{}
	order := []string{}

	f, err := os.Open(zonePath)
	if err != nil {
		return fmt.Errorf("read the tzdata zone table: %w", err)
	}
	defer func() { _ = f.Close() }()

	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		line := scanner.Text()
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Split(line, "\t")
		if len(fields) < 3 {
			continue
		}
		id := fields[2]
		if _, seen := zones[id]; seen {
			continue
		}
		codes := make([]string, 0, 2)
		for _, code := range strings.Split(fields[0], ",") {
			code = strings.ToLower(strings.TrimSpace(code))
			if len(code) == 2 {
				codes = append(codes, code)
			}
		}
		comment := ""
		if len(fields) > 3 {
			comment = fields[3]
		}
		zones[id] = &shared.Timezone{ID: id, Countries: codes, Comment: comment}
		order = append(order, id)
	}
	if err := scanner.Err(); err != nil {
		return err
	}

	// A PreferredZone that is a tzdata *link* (not a zone1970 row) still has to be
	// selectable: it is the name the install writes for that country. Attach it to
	// the country it was curated for.
	for code, id := range shared.PreferredZone {
		if _, seen := zones[id]; seen {
			continue
		}
		zones[id] = &shared.Timezone{ID: id, Countries: []string{code}}
		order = append(order, id)
	}

	// UTC is the clock with no city — the worldwide location's answer, and a
	// legitimate choice for a machine that should not assume a region.
	if _, seen := zones["UTC"]; !seen {
		zones["UTC"] = &shared.Timezone{ID: "UTC"}
		order = append(order, "UTC")
	}

	table := make([]shared.Timezone, 0, len(order))
	for _, id := range order {
		table = append(table, *zones[id])
	}
	sort.Slice(table, func(i, j int) bool { return table[i].ID < table[j].ID })

	if err := writeTable(table); err != nil {
		return err
	}
	fmt.Printf("Wrote %d time zones (from %s).\n", len(table), zonePath)
	return nil
}

func writeTable(table []shared.Timezone) error {
	out, err := os.Create("timezones_table.go")
	if err != nil {
		return err
	}
	defer func() { _ = out.Close() }()

	w := bufio.NewWriter(out)
	defer func() { _ = w.Flush() }()

	_, _ = w.WriteString(`// Code generated by timezones_gen.go. DO NOT EDIT.
//
// The time zones the installer offers: every civil clock tzdata has kept since
// 1970, plus UTC, plus the local names PreferredZone writes for countries whose
// only tzdata row is named after a neighbour's city. Regenerate with
//
//	go run ./backend/shared/timezones_gen.go
//
// Countries lists the ISO 3166-1 codes tzdata names in the row (lowercased), so
// a location's own clocks can be listed without re-reading the zone table.

package shared

// timezoneTable is every time zone the installer can offer, sorted by ID.
var timezoneTable = []Timezone{
`)
	for _, z := range table {
		_, _ = fmt.Fprintf(w, "\t{ID: %q, Countries: %s, Comment: %q},\n",
			z.ID, goStringSlice(z.Countries), z.Comment)
	}
	_, _ = w.WriteString("}\n")

	return w.Flush()
}

func goStringSlice(s []string) string {
	if len(s) == 0 {
		return "nil"
	}
	parts := make([]string, len(s))
	for i, v := range s {
		parts[i] = fmt.Sprintf("%q", v)
	}
	return "[]string{" + strings.Join(parts, ", ") + "}"
}
