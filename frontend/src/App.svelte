<script lang="ts">
	import { fly } from 'svelte/transition';
	import { quadOut } from 'svelte/easing';
	import AppHeader from '$components/AppHeader.svelte';
	import AppFooter from '$components/AppFooter.svelte';
	import ConfirmDialog from '$components/ConfirmDialog.svelte';

	import WelcomePage from '$pages/WelcomePage.svelte';
	import UserAccountPage from '$pages/UserAccountPage.svelte';
	import DiskSelectionPage from '$pages/DiskSelectionPage.svelte';
	import ConfirmationPage from '$pages/ConfirmationPage.svelte';
	import InstallationPage from '$pages/InstallationPage.svelte';
	import FinishPage from '$pages/FinishPage.svelte';

	import type { PageID } from '$lib/types';
	import { PAGE_IDS, PAGES_NO_NAV, TOTAL_PAGES } from '$lib/types';
	import { goNext, goBack, finish } from '$lib/navigation';
	// @ts-expect-error — generated by Wails
	import { GetStartPage, ClearStartPage } from '@wails/go/app/App.js';

	// State
	let currentPage = $state(0);
	let errorMessage = $state<string | null>(null);
	let direction = $state<'forward' | 'backward'>('forward');

	// Auto-dismiss error banner after 5 seconds
	let dismissTimer: ReturnType<typeof setTimeout> | null = null;

	$effect(() => {
		if (!errorMessage) return;
		if (dismissTimer) clearTimeout(dismissTimer);
		dismissTimer = setTimeout(() => {
			errorMessage = null;
			dismissTimer = null;
		}, 5000);
		return () => {
			if (dismissTimer) {
				clearTimeout(dismissTimer);
				dismissTimer = null;
			}
		};
	});

	// Jump to start page on init if configured
	async function initStartPage(): Promise<void> {
		try {
			const startPage = await GetStartPage();
			if (startPage >= 0 && startPage < TOTAL_PAGES) {
				currentPage = startPage;
				await ClearStartPage();
			}
		} catch {
			// Ignore errors — start page not configured
		}
	}

	initStartPage();

	async function handleNext(e?: Event) {
		// Run validation first
		const error = await goNext(currentPage);
		if (error) {
			errorMessage = error;
			return;
		}

		// Check if a child component cancelled the navigation
		if (e?.defaultPrevented) return;

		direction = 'forward';
		currentPage++;
	}

	async function handleBack() {
		if (currentPage === PAGE_IDS.WELCOME) return;

		const error = await goBack(currentPage);
		if (error) {
			errorMessage = error;
			return;
		}

		direction = 'backward';
		currentPage--;
	}

	async function handleFinish() {
		errorMessage = await finish();
	}

	// Subscribe to navigation events from footer and pages
	$effect(() => {
		const onGoNext = (e: Event) => { handleNext(e); };
		const onGoBack = (e: Event) => { if (!e.defaultPrevented) handleBack(); };
		const onFinish = (e: Event) => { if (!e.defaultPrevented) handleFinish(); };

		document.addEventListener('go-next', onGoNext);
		document.addEventListener('go-back', onGoBack);
		document.addEventListener('finish', onFinish);

		return () => {
			document.removeEventListener('go-next', onGoNext);
			document.removeEventListener('go-back', onGoBack);
			document.removeEventListener('finish', onFinish);
		};
	});
</script>

<div class="app-layout">
	<AppHeader {currentPage} />

	<main class="content-area">
		{#key currentPage}
			<div class="page-content" transition:fly={{ x: direction === 'forward' ? -40 : 40, duration: 250, easing: quadOut }}>
				{#if errorMessage}
					<div class="error-banner">{errorMessage}</div>
				{/if}
				{#if currentPage === PAGE_IDS.WELCOME}
					<WelcomePage />
				{:else if currentPage === PAGE_IDS.USER_ACCOUNT}
					<UserAccountPage />
				{:else if currentPage === PAGE_IDS.DISK_SELECTION}
					<DiskSelectionPage />
				{:else if currentPage === PAGE_IDS.CONFIRMATION}
					<ConfirmationPage />
				{:else if currentPage === PAGE_IDS.INSTALLATION}
					<InstallationPage />
				{:else if currentPage === PAGE_IDS.FINISH}
					<FinishPage />
				{/if}
			</div>
		{/key}
	</main>

	<ConfirmDialog />

	{#if !PAGES_NO_NAV.has(currentPage as PageID)}
		<AppFooter {currentPage} />
	{/if}
</div>

