<script lang="ts">
	import { fly } from 'svelte/transition';
	import { backOut } from 'svelte/easing';

	import AppHeader from '$components/AppHeader.svelte';
	import AppFooter from '$components/AppFooter.svelte';
	import ConfirmDialog from '$components/ConfirmDialog.svelte';

	import WelcomePage from '$pages/WelcomePage.svelte';
	import UserAccountPage from '$pages/UserAccountPage.svelte';
	import DiskSelectionPage from '$pages/DiskSelectionPage.svelte';
	import ConfirmationPage from '$pages/ConfirmationPage.svelte';
	import InstallationPage from '$pages/InstallationPage.svelte';
	import FinishPage from '$pages/FinishPage.svelte';

	import type { PageID } from '$lib/types';
	import { PAGE_IDS, PAGES_NO_NAV, TOTAL_PAGES } from '$lib/types';
	import { goNext, goBack, finish } from '$lib/navigation';
	import { installState, navState, getIsDryRun, setDryRun } from '$lib/store.svelte';
	import { getIsRTL } from '$lib/i18n/index.svelte';

	// @ts-expect-error — generated by Wails
	import { GetStartPage, ClearStartPage, GetDryRun } from '@wails/go/gui/App.js';

	// Jump to start page on init if configured
	async function initStartPage(): Promise<void> {
		try {
			const startPage = await GetStartPage();
			if (startPage >= 0 && startPage < TOTAL_PAGES) {
				navState.currentPage = startPage;
				await ClearStartPage();
			}
		} catch {
			// Ignore errors — start page not configured
		}

		try {
			setDryRun(await GetDryRun());
		} catch {
			// Ignore errors — dry run state not available
		}
	}

	initStartPage();

	// Listen for navigation events (from pages/dialogs)
	$effect(() => {
		const onNext = () => { handleNext(); };
		const onBack = () => { handleBack(); };
		const onConfirm = () => { handleNext(); };
		document.addEventListener('go-next', onNext);
		document.addEventListener('go-back', onBack);
		document.addEventListener('go-next-confirmed', onConfirm);
		return () => {
			document.removeEventListener('go-next', onNext);
			document.removeEventListener('go-back', onBack);
			document.removeEventListener('go-next-confirmed', onConfirm);
		};
	});

	async function handleNext(): Promise<void> {
		const error = await goNext(navState.currentPage);
		if (error) {
			console.error(`[App] Validation failed: ${error}`);
			return;
		}
	}

	async function handleBack(): Promise<void> {
		if (navState.currentPage === PAGE_IDS.WELCOME) return;
		await goBack(navState.currentPage);
	}

	async function handleFinish(): Promise<void> {
		const error = await finish();
		if (error) {
			console.error(`[App] Finish failed: ${error}`);
		}
	}

</script>

<div class="app-layout" dir={getIsRTL() ? 'rtl' : 'ltr'}>
	<AppHeader currentPage={navState.currentPage} />
	<main class="content-area">
		{#key navState.currentPage}
			<div
				class="page"
				transition:fly={{ x: navState.direction === 'forward' ? -80 : 80, duration: 350, easing: backOut }}
			>
				{#if navState.currentPage === PAGE_IDS.WELCOME}
					<WelcomePage />
				{:else if navState.currentPage === PAGE_IDS.USER_ACCOUNT}
					<UserAccountPage />
				{:else if navState.currentPage === PAGE_IDS.DISK_SELECTION}
					<DiskSelectionPage />
				{:else if navState.currentPage === PAGE_IDS.CONFIRMATION}
					<ConfirmationPage />
				{:else if navState.currentPage === PAGE_IDS.INSTALLATION}
					<InstallationPage />
				{:else if navState.currentPage === PAGE_IDS.FINISH}
					<FinishPage />
				{/if}
			</div>
		{/key}
	</main>

	<ConfirmDialog />
	{#if !PAGES_NO_NAV.has(navState.currentPage as PageID)}
		<AppFooter currentPage={navState.currentPage} onNext={handleNext} onBack={handleBack} onFinish={handleFinish} />
	{/if}
</div>

