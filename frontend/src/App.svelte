<script lang="ts">
	import AppHeader from '$components/AppHeader.svelte';
	import AppFooter from '$components/AppFooter.svelte';
	import PageTransition from '$components/PageTransition.svelte';

	import WelcomePage from '$pages/WelcomePage.svelte';
	import UserAccountPage from '$pages/UserAccountPage.svelte';
	import DiskSelectionPage from '$pages/DiskSelectionPage.svelte';
	import ConfirmationPage from '$pages/ConfirmationPage.svelte';
	import InstallationPage from '$pages/InstallationPage.svelte';
	import FinishPage from '$pages/FinishPage.svelte';

	import type { TransitionDirection } from '$lib/types';
	import { goNext, goBack, finish } from '$lib/navigation';
	import { showConfirmDialog, diskSelectionData } from '$lib/store';
	// @ts-expect-error — generated by Wails
	import { LogInfo } from '@wails/runtime/runtime';
	// @ts-expect-error — generated by Wails
	import { GetStartPage, ClearStartPage } from '@wails/go/app/App.js';

	// State
	let currentPage = $state(0);
	let isTransitioning = $state(false);
	let errorMessage = $state<string | null>(null);

	// Animation state
	let animKey = $state(0);
	let animDirection = $state<TransitionDirection>('forward');
	let animLeaving = $state(false);
	let animEntering = $state(false);
	let animEnteringDone = $state(false);

	// Jump to start page on init if configured
	async function initStartPage(): Promise<void> {
		try {
			const startPage = await GetStartPage();
			if (startPage >= 0 && startPage < 6) {
				currentPage = startPage;
				animKey++;
				await ClearStartPage();
			}
		} catch {
			// Ignore errors — start page not configured
		}
	}

	initStartPage();

	async function startTransition(direction: TransitionDirection, newPage: number) {
		if (isTransitioning) return;
		isTransitioning = true;
		animDirection = direction;
		animLeaving = true;

		await new Promise<void>((resolve) => {
			setTimeout(() => {
				animKey++;
				animLeaving = false;
				animEntering = true;
				currentPage = newPage;
				errorMessage = null;

				setTimeout(() => {
					animEnteringDone = true;
				}, 200);
				setTimeout(() => {
					animEntering = false;
					animEnteringDone = false;
					isTransitioning = false;
					resolve();
				}, 450);
			}, 200);
		});
	}

	async function handleNext(e?: Event) {
		if (isTransitioning) return;

		// Run validation first
		const error = await goNext(currentPage);
		if (error) {
			errorMessage = error;
			return; // Don't navigate if validation fails
		}

		// Check if a child component (e.g., ConfirmationPage) cancelled the navigation
		if (e?.defaultPrevented) return;

		// Only start animation after validation passes
		await startTransition('forward', currentPage + 1);
	}

	async function handleBack() {
		if (isTransitioning || currentPage === 0) return;

		const error = await goBack(currentPage);
		if (error) {
			errorMessage = error;
			return;
		}

		await startTransition('backward', currentPage - 1);
	}

	async function handleFinish() {
		errorMessage = await finish();
	}

	// Subscribe to navigation events from footer and pages
	$effect(() => {
		const onGoNext = (e: Event) => { handleNext(e); };
		const onGoBack = (e: Event) => { if (!e.defaultPrevented) handleBack(); };
		const onFinish = (e: Event) => { if (!e.defaultPrevented) handleFinish(); };

		document.addEventListener('go-next', onGoNext);
		document.addEventListener('go-back', onGoBack);
		document.addEventListener('finish', onFinish);

		return () => {
			document.removeEventListener('go-next', onGoNext);
			document.removeEventListener('go-back', onGoBack);
			document.removeEventListener('finish', onFinish);
		};
	});
</script>

<div class="app-layout">
	<AppHeader {currentPage} />

	<main class="content-area">
		{#if errorMessage}
			<div class="error-banner">{errorMessage}</div>
		{/if}

		<PageTransition
			contentKey={animKey}
			direction={animDirection}
			leaving={animLeaving}
			entering={animEntering}
			enteringDone={animEnteringDone}
		>
			{#if currentPage === 0}
				<WelcomePage />
			{:else if currentPage === 1}
				<UserAccountPage />
			{:else if currentPage === 2}
				<DiskSelectionPage />
			{:else if currentPage === 3}
				<ConfirmationPage />
			{:else if currentPage === 4}
				<InstallationPage />
			{:else if currentPage === 5}
				<FinishPage />
			{/if}
		</PageTransition>
	</main>

	<!-- Confirmation Dialog – rendered here to cover header + footer -->
	{#if $showConfirmDialog}
		<div class="dialog-overlay" onclick={() => showConfirmDialog.set(false)} onkeydown={(e) => { if (e.key === 'Escape') showConfirmDialog.set(false); }} role="presentation">
			<div class="dialog" onclick={(e) => e.stopPropagation()} onkeydown={(e) => e.stopPropagation()} role="dialog" aria-modal="true" aria-labelledby="dialog-title" tabindex="-1">
				<div class="dialog-icon">⚠️</div>
				<h2 id="dialog-title" class="dialog-title">Confirm Installation</h2>
				<p class="dialog-message">
					Are you sure you want to install AestheticOS on
					<strong> {$diskSelectionData.disk?.model || 'Unknown'} </strong>?
					<br />
					<strong>All data on this disk will be permanently erased.</strong>
				</p>
				<div class="dialog-actions">
					<button type="button" class="btn-cancel" onclick={() => {
					showConfirmDialog.set(false);
				}}>
						Cancel
					</button>
					<button type="button" class="btn-confirm" onclick={() => {
						LogInfo('[App] User confirmed installation');
						document.dispatchEvent(new CustomEvent('go-next', { cancelable: true }));
						setTimeout(() => showConfirmDialog.set(false), 0);
					}}>
						Yes, Erase & Install
					</button>
				</div>
			</div>
		</div>
	{/if}

	{#if currentPage > 0 && currentPage !== 4}
		<AppFooter {currentPage} />
	{/if}
</div>

