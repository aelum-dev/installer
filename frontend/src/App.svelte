<script lang="ts">
	import AppHeader from '$components/AppHeader.svelte';
	import AppFooter from '$components/AppFooter.svelte';
	import PageTransition from '$components/PageTransition.svelte';

	import WelcomePage from '$pages/WelcomePage.svelte';
	import UserAccountPage from '$pages/UserAccountPage.svelte';
	import DiskSelectionPage from '$pages/DiskSelectionPage.svelte';
	import InstallationPage from '$pages/InstallationPage.svelte';
	import FinishPage from '$pages/FinishPage.svelte';

	import type { TransitionDirection } from '$lib/types';
	import { userAccountData } from '$lib/store';
	import { get } from 'svelte/store';
	// @ts-expect-error — generated by Wails
	import { CanGoNext, CanGoBack, SetCurrentPage, ValidateUserAccount } from '@wails/go/main/App.js';

	let currentPage = $state(0);
	let isTransitioning = $state(false);
	let errorMessage = $state('');

	$effect(() => {
		const handler = () => goToNext();
		document.addEventListener('go-next', handler);
		return () => document.removeEventListener('go-next', handler);
	});

	// Animation state
	let animKey = $state(0);
	let animDirection = $state<TransitionDirection>('forward');
	let animLeaving = $state(false);
	let animEntering = $state(false);

	async function goToNext() {
		if (isTransitioning) return;

		// Notify each page so it can log its gathered data before leaving
		document.dispatchEvent(new CustomEvent('page-leave'));

		const success = await validateNext();
		if (!success) return;

		await animateTransition('forward');
		currentPage++;
		errorMessage = '';
	}

	async function goToBack() {
		if (isTransitioning || currentPage === 0) return;

		// Sync with Go backend
		await SetCurrentPage(currentPage - 1);
		errorMessage = '';

		isTransitioning = true;
		await animateTransition('backward');
		currentPage--;
		isTransitioning = false;
	}

	async function validateNext(): Promise<boolean> {
		try {
			// Page-specific validation via Go backend
			if (currentPage === 1) {
				const data = get(userAccountData);
				await ValidateUserAccount({
					username: data.username,
					password: data.password,
					confirmPassword: data.confirmPassword,
				});
			}

			const canGo = await CanGoNext();
			if (!canGo) {
				errorMessage = 'Validation failed. Please fix the issues above.';
				return false;
			}

			await SetCurrentPage(currentPage + 1);
			return true;
		} catch (err) {
			errorMessage = err instanceof Error ? err.message : 'Unknown error';
			return false;
		}
	}

	async function animateTransition(direction: TransitionDirection): Promise<void> {
		isTransitioning = true;
		animDirection = direction;
		animLeaving = true;

		// Wait for leave animation (200ms), then swap content and start enter
		await new Promise<void>((resolve) => {
			setTimeout(() => {
				animKey++; // triggers re-render with new key
				animLeaving = false;
				animEntering = true;

				// Wait for enter animation to complete (200ms)
				setTimeout(resolve, 200);
			}, 200);
		});

		animEntering = false;
		isTransitioning = false;
	}
</script>

<div class="app-layout">
	<AppHeader {currentPage} />

	<main class="content-area">
		{#if errorMessage}
			<div class="error-banner">{errorMessage}</div>
		{/if}

		<PageTransition
			contentKey={animKey}
			direction={animDirection}
			leaving={animLeaving}
			entering={animEntering}
		>
			{#if currentPage === 0}
				<WelcomePage />
			{:else if currentPage === 1}
				<UserAccountPage />
			{:else if currentPage === 2}
				<DiskSelectionPage />
			{:else if currentPage === 3}
				<InstallationPage />
			{:else if currentPage === 4}
				<FinishPage />
			{/if}
		</PageTransition>
	</main>

	{#if currentPage > 0}
		<AppFooter {currentPage} onBack={goToBack} onNext={goToNext} />
	{/if}
</div>

