<script lang="ts">
	import AppHeader from '$components/AppHeader.svelte';
	import AppFooter from '$components/AppFooter.svelte';
	import PageTransition from '$components/PageTransition.svelte';

	import WelcomePage from '$pages/WelcomePage.svelte';
	import UserAccountPage from '$pages/UserAccountPage.svelte';
	import DiskSelectionPage from '$pages/DiskSelectionPage.svelte';
	import ConfirmationPage from '$pages/ConfirmationPage.svelte';
	import InstallationPage from '$pages/InstallationPage.svelte';
	import FinishPage from '$pages/FinishPage.svelte';

	import type { TransitionDirection } from '$lib/types';
	import { userAccountData, diskSelectionData } from '$lib/store';
	import { get } from 'svelte/store';
	// @ts-expect-error — generated by Wails
	import { LogInfo as WailsLogInfo, LogError as WailsLogError } from '@wails/runtime/runtime';

	// Safe logging wrapper - works in both Wails and dev mode
	function logInfo(msg: string): void {
		try { WailsLogInfo(msg); } catch { /* dev mode: no Wails runtime */ }
	}
	function logError(msg: string): void {
		try { WailsLogError(msg); } catch { /* dev mode: no Wails runtime */ }
	}
	// @ts-expect-error — generated by Wails
	import { CanGoNext, CanGoBack, SetCurrentPage, ValidateUserAccount, ValidateDiskSelection, SetStartPage, GetStartPage, ClearStartPage, RebootAndClose } from '@wails/go/app/App.js';

	let currentPage = $state(0);
	let isTransitioning = $state(false);
	let errorMessage = $state('');
	let hasStarted = $state(false); // prevents double-jump
	let showDebug = $state(false);
	let debugMessage = $state('');

	// Jump to start page on init if configured
	async function initStartPage(): Promise<void> {
		if (hasStarted) return;
		hasStarted = true;

		try {
			const startPage = await GetStartPage();
			if (startPage >= 0 && startPage < 6) {
				// Skip directly to the configured page, bypassing all validation
				currentPage = startPage;
				animKey++;
				await SetCurrentPage(startPage);
				await ClearStartPage();
			}
		} catch {
			// Ignore errors — start page not configured
		}
	}

	initStartPage();

	$effect(() => {
		const handler = () => goToNext();
		document.addEventListener('go-next', handler);
		return () => document.removeEventListener('go-next', handler);
	});

	// Animation state
	let animKey = $state(0);
	let animDirection = $state<TransitionDirection>('forward');
	let animLeaving = $state(false);
	let animEntering = $state(false);

	async function goToNext() {
		if (isTransitioning) return;

		// Notify each page so it can log its gathered data before leaving
		document.dispatchEvent(new CustomEvent('page-leave'));

		const success = await validateNext();
		if (!success) return;

		await animateTransition('forward');
		currentPage++;
		errorMessage = '';
	}

	async function goToBack() {
		if (isTransitioning || currentPage === 0) return;

		isTransitioning = true;
		await animateTransition('backward');
		currentPage--;
		errorMessage = '';
		isTransitioning = false;

		// Sync with Go backend
		await SetCurrentPage(currentPage);
	}

	async function handleFinish() {
		try {
			await RebootAndClose();
		} catch (err) {
			errorMessage = err instanceof Error ? err.message : 'Failed to reboot';
		}
	}

	async function validateNext(): Promise<boolean> {
		try {
			// DEBUG: Log all stored data before validation
			const allData = {
				currentPage,
				userAccountData: get(userAccountData),
				diskSelectionData: get(diskSelectionData),
			};

			if (currentPage === 1) {
				logInfo(`[DEBUG] Page 1 -> User Account Data: ${JSON.stringify(allData.userAccountData, null, 2)}`);
				debugMessage = `USER ACCOUNT DATA:\n${JSON.stringify(allData.userAccountData, null, 2)}`;
				showDebug = true;

				const data = get(userAccountData);
				await ValidateUserAccount({
					username: data.username,
					password: data.password,
					confirmPassword: data.confirmPassword,
				});
			}

			if (currentPage === 2) {
				logInfo(`[DEBUG] Page 2 -> Disk Selection Data: ${JSON.stringify(allData.diskSelectionData, null, 2)}`);
				debugMessage = `DISK SELECTION DATA:\n${JSON.stringify(allData.diskSelectionData, null, 2)}`;
				showDebug = true;

				const data = get(diskSelectionData);
				await ValidateDiskSelection({ diskId: data.diskId });
			}

			const canGo = await CanGoNext();
			if (!canGo) {
				errorMessage = 'Validation failed. Please fix the issues above.';
				return false;
			}

			await SetCurrentPage(currentPage + 1);
			return true;
		} catch (err) {
			errorMessage = err instanceof Error ? err.message : 'Unknown error';
			return false;
		}
	}

	async function animateTransition(direction: TransitionDirection): Promise<void> {
		isTransitioning = true;
		animDirection = direction;
		animLeaving = true;

		// Wait for leave animation (200ms), then swap content and start enter
		await new Promise<void>((resolve) => {
			setTimeout(() => {
				animKey++; // triggers re-render with new key
				animLeaving = false;
				animEntering = true;

				// Wait for enter animation to complete (200ms)
				setTimeout(resolve, 200);
			}, 200);
		});

		animEntering = false;
		isTransitioning = false;
	}
</script>

<div class="app-layout">
	<AppHeader {currentPage} />

	<!-- Debug Panel Toggle -->
	<button
		type="button"
		class="debug-toggle"
		onclick={() => { showDebug = !showDebug; if (showDebug) { debugMessage = `ALL STORED DATA (Page ${currentPage}):\n\nUser Account Data:\n${JSON.stringify(get(userAccountData), null, 2)}\n\nDisk Selection Data:\n${JSON.stringify(get(diskSelectionData), null, 2)}`; logInfo(`[DEBUG] Show debug panel - Page ${currentPage}: ${JSON.stringify({userAccount: get(userAccountData), diskSelection: get(diskSelectionData)})}`); } }}
		title="Toggle debug view"
	>
		🐛 Debug
	</button>

	<!-- Debug Panel -->
	{#if showDebug}
		<div class="debug-panel">
			<div class="debug-header">
				<span>🐛 Debug - Page {currentPage} ({currentPage === 0 ? 'Welcome' : currentPage === 1 ? 'User Account' : currentPage === 2 ? 'Disk Selection' : currentPage === 3 ? 'Confirmation' : currentPage === 4 ? 'Installation' : 'Finish'})</span>
				<button type="button" class="debug-close" onclick={() => showDebug = false}>✕</button>
			</div>
			<pre class="debug-content">{debugMessage}</pre>
		</div>
	{/if}

	<main class="content-area">
		{#if errorMessage}
			<div class="error-banner">{errorMessage}</div>
		{/if}

		<PageTransition
			contentKey={animKey}
			direction={animDirection}
			leaving={animLeaving}
			entering={animEntering}
		>
			{#if currentPage === 0}
				<WelcomePage />
			{:else if currentPage === 1}
				<UserAccountPage />
			{:else if currentPage === 2}
				<DiskSelectionPage />
			{:else if currentPage === 3}
				<ConfirmationPage />
			{:else if currentPage === 4}
				<InstallationPage />
			{:else if currentPage === 5}
				<FinishPage />
			{/if}
		</PageTransition>
	</main>

	{#if currentPage > 0 && currentPage !== 4}
		<AppFooter {currentPage} onBack={goToBack} onNext={goToNext} onFinish={handleFinish} />
	{/if}
</div>

