import { describe, it, expect, vi, beforeEach } from 'vitest';
import { userAccountData, diskSelectionData } from '$lib/state.svelte';
import { goNext, goBack } from '$lib/navigation';
import { PAGE_IDS } from '$lib/types';

// Mock Wails Go bindings
vi.mock('@wails/go/gui/App.js', () => ({
	SetCurrentPage: vi.fn(() => Promise.resolve()),
	ValidateUserAccount: vi.fn(() => Promise.resolve()),
	SaveUserAccount: vi.fn(() => Promise.resolve()),
	ValidateDiskSelection: vi.fn(() => Promise.resolve()),
	SaveDiskSelection: vi.fn(() => Promise.resolve()),
}));

// Mock Wails runtime
vi.mock('@wails/runtime/runtime', () => ({
	LogInfo: vi.fn(),
	LogError: vi.fn(),
}));

describe('App navigation', () => {
	beforeEach(() => {
		vi.clearAllMocks();
		userAccountData.username = '';
		userAccountData.password = '';
		userAccountData.confirmPassword = '';
		diskSelectionData.diskId = '';
		diskSelectionData.disk = null;
		diskSelectionData.fileSystem = '';
	});

	describe('goNext', () => {
		it('should advance from Welcome to UserAccount', async () => {
			const result = await goNext(PAGE_IDS.WELCOME);
			expect(result).toBeNull();
		});

		it('should validate UserAccount page before advancing', async () => {
			// @ts-expect-error — generated by Wails, not in source tree
			const { ValidateUserAccount } = await import('@wails/go/gui/App.js');
			vi.mocked(ValidateUserAccount).mockRejectedValueOnce(new Error('invalid'));
			const result = await goNext(PAGE_IDS.USER_ACCOUNT);
			expect(result).toBe('Please complete all required fields to continue.');
		});

		it('should validate DiskSelection page before advancing', async () => {
			// @ts-expect-error — generated by Wails, not in source tree
			const { ValidateDiskSelection } = await import('@wails/go/gui/App.js');
			vi.mocked(ValidateDiskSelection).mockRejectedValueOnce(new Error('invalid'));
			const result = await goNext(PAGE_IDS.DISK_SELECTION);
			expect(result).toBe('Please select a disk to continue.');
		});

		it('should save user account data when advancing from UserAccount', async () => {
			userAccountData.username = 'testuser';
			userAccountData.password = 'pass123';
			userAccountData.confirmPassword = 'pass123';
			await goNext(PAGE_IDS.USER_ACCOUNT);
			expect(userAccountData.username).toBe('testuser');
		});
	});

	describe('goBack', () => {
		it('should go back from DiskSelection to UserAccount', async () => {
			const result = await goBack(PAGE_IDS.DISK_SELECTION);
			expect(result).toBeNull();
		});

		it('should clear disk selection when going back from Confirmation', async () => {
			diskSelectionData.diskId = '/dev/sda';
			diskSelectionData.disk = { name: 'sda', path: '/dev/sda', size: '1000000000', type: 'disk', model: 'Test', vendor: '', rotational: false, readonly: false, fstype: null, mountpoint: null, serial: '', trans: '', isRemovable: false } as any;
			await goBack(PAGE_IDS.CONFIRMATION);
			expect(diskSelectionData.diskId).toBe('');
			expect(diskSelectionData.disk).toBeNull();
		});
	});
});
